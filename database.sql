-- Preserve existing measurements when upgrading from the one-sensor-per-row layout.
DO $$
DECLARE
    has_sensor_column BOOLEAN;
    has_slice_column BOOLEAN;
    fatia_position INTEGER;
BEGIN
    SELECT EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = 'amostras'
          AND column_name = 'sensor'
    ) INTO has_sensor_column;

    IF has_sensor_column THEN
        ALTER TABLE amostras RENAME TO amostras_legacy;
        ALTER TABLE amostras_legacy
            RENAME CONSTRAINT amostras_pkey TO amostras_legacy_pkey;
    ELSE
        SELECT EXISTS (
            SELECT 1
            FROM information_schema.columns
            WHERE table_schema = current_schema()
              AND table_name = 'amostras'
              AND column_name = 'slice'
        ) INTO has_slice_column;

        SELECT ordinal_position INTO fatia_position
        FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = 'amostras'
          AND column_name = 'fatia';

        IF has_slice_column OR (fatia_position IS NOT NULL AND fatia_position <> 3) THEN
            ALTER TABLE amostras RENAME TO amostras_legacy_wide;
            ALTER TABLE amostras_legacy_wide
                RENAME CONSTRAINT amostras_pkey TO amostras_legacy_wide_pkey;
        END IF;
    END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS amostras (
    serie BIGINT NOT NULL REFERENCES serie (id) ON DELETE CASCADE,
    seq INTEGER NOT NULL,
    fatia INTEGER,
    acel_x1 DOUBLE PRECISION NOT NULL,
    acel_y1 DOUBLE PRECISION NOT NULL,
    acel_z1 DOUBLE PRECISION NOT NULL,
    acel_x2 DOUBLE PRECISION NOT NULL,
    acel_y2 DOUBLE PRECISION NOT NULL,
    acel_z2 DOUBLE PRECISION NOT NULL,
    mic DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (serie, seq)
);

DO $$
BEGIN
    IF to_regclass('amostras_legacy') IS NOT NULL THEN
        INSERT INTO amostras (
            serie, seq, fatia, acel_x1, acel_y1, acel_z1,
            acel_x2, acel_y2, acel_z2, mic
        )
        SELECT
            legacy.serie,
            legacy.seq,
            MAX(splitdata.split_index),
            MAX(legacy.value) FILTER (WHERE sensor.name = 'acelerometro 1 X'),
            MAX(legacy.value) FILTER (WHERE sensor.name = 'acelerometro 1 Y'),
            MAX(legacy.value) FILTER (WHERE sensor.name = 'acelerometro 1 Z'),
            MAX(legacy.value) FILTER (WHERE sensor.name = 'acelerometro 2 X'),
            MAX(legacy.value) FILTER (WHERE sensor.name = 'acelerometro 2 Y'),
            MAX(legacy.value) FILTER (WHERE sensor.name = 'acelerometro 2 Z'),
            MAX(legacy.value) FILTER (WHERE sensor.name = 'microfone')
        FROM amostras_legacy AS legacy
        INNER JOIN sensor ON sensor.id = legacy.sensor
        LEFT JOIN splitdata
            ON splitdata.serie = legacy.serie
           AND legacy.seq > splitdata.sample_start
           AND legacy.seq <= splitdata.sample_end
        GROUP BY legacy.serie, legacy.seq;

        DROP TABLE amostras_legacy;
    END IF;

    IF to_regclass('amostras_legacy_wide') IS NOT NULL THEN
        IF EXISTS (
            SELECT 1
            FROM information_schema.columns
            WHERE table_schema = current_schema()
              AND table_name = 'amostras_legacy_wide'
              AND column_name = 'fatia'
        ) THEN
            INSERT INTO amostras (
                serie, seq, fatia, acel_x1, acel_y1, acel_z1,
                acel_x2, acel_y2, acel_z2, mic
            )
            SELECT
                serie, seq, fatia, acel_x1, acel_y1, acel_z1,
                acel_x2, acel_y2, acel_z2, mic
            FROM amostras_legacy_wide;
        ELSE
            INSERT INTO amostras (
                serie, seq, fatia, acel_x1, acel_y1, acel_z1,
                acel_x2, acel_y2, acel_z2, mic
            )
            SELECT
                serie, seq, "slice", acel_x1, acel_y1, acel_z1,
                acel_x2, acel_y2, acel_z2, mic
            FROM amostras_legacy_wide;
        END IF;

        DROP TABLE amostras_legacy_wide;
    END IF;
END;
$$;

